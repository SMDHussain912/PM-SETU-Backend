import {Router} from "express";
import {requireAuth} from "../../middleware/auth.middleware";
import {requireRoles} from "../../middleware/rbac.middleware";
import {requireResourceScope} from "../../middleware/scope.middleware";
import {validate} from "../../middleware/validate.middleware";
import {ROLE_CODES} from "../roles/role.constants";
import * as c from "./spv-workflow.controller";
import {spvReportParamsSchema,spvWorkflowParamsSchema,createSpvActivitySchema,createSpvReportSchema,reviewSpvReportSchema,updateSpvReportSchema} from "./spv-workflow.schema";
const r=Router();
const editors=[ROLE_CODES.SPV_USER,ROLE_CODES.SUPER_ADMIN,ROLE_CODES.STATE_PMU_ADMIN];
const reviewers=[ROLE_CODES.CLUSTER_ADMIN,ROLE_CODES.STATE_PMU_ADMIN,ROLE_CODES.SUPER_ADMIN];
r.use(requireAuth);
r.get("/:id/activities",requireRoles(...[...editors,...reviewers]),validate({params:spvWorkflowParamsSchema}),requireResourceScope("SPV"),c.activities);
r.post("/:id/activities",requireRoles(...editors),validate({params:spvWorkflowParamsSchema,body:createSpvActivitySchema}),requireResourceScope("SPV"),c.addActivity);
r.get("/:id/submissions",requireRoles(...[...editors,...reviewers]),validate({params:spvWorkflowParamsSchema}),requireResourceScope("SPV"),c.reports);
r.post("/:id/submissions",requireRoles(...editors),validate({params:spvWorkflowParamsSchema,body:createSpvReportSchema}),requireResourceScope("SPV"),c.createReport);
r.patch("/:id/submissions/:submissionId",requireRoles(...editors),validate({params:spvReportParamsSchema,body:updateSpvReportSchema}),requireResourceScope("SPV"),c.updateReport);
r.post("/:id/submissions/:submissionId/submit",requireRoles(...editors),validate({params:spvReportParamsSchema}),requireResourceScope("SPV"),c.submitReport);
r.post("/:id/submissions/:submissionId/review",requireRoles(...reviewers),validate({params:spvReportParamsSchema,body:reviewSpvReportSchema}),requireResourceScope("SPV"),c.reviewReport);
export default r;
