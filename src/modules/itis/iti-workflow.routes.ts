import {Router} from "express";
import {requireAuth} from "../../middleware/auth.middleware";
import {requireRoles} from "../../middleware/rbac.middleware";
import {requireResourceScope} from "../../middleware/scope.middleware";
import {validate} from "../../middleware/validate.middleware";
import {ROLE_CODES} from "../roles/role.constants";
import * as controller from "./iti-workflow.controller";
import {itiIdParamsSchema} from "./iti.schema";
import {createItiSubmissionSchema,itiSubmissionParamsSchema,reviewItiSubmissionSchema,updateItiProfileSchema,updateItiSubmissionSchema} from "./iti-workflow.schema";

const router=Router();
const instituteEditors=[ROLE_CODES.HUB_ITI_USER,ROLE_CODES.SPOKE_ITI_USER,ROLE_CODES.SUPER_ADMIN,ROLE_CODES.STATE_PMU_ADMIN];
const reviewers=[ROLE_CODES.CLUSTER_ADMIN,ROLE_CODES.STATE_PMU_ADMIN,ROLE_CODES.SUPER_ADMIN];
router.use(requireAuth);
router.patch("/:id/profile",requireRoles(...instituteEditors),requireResourceScope("ITI"), validate({params:itiIdParamsSchema,body:updateItiProfileSchema}),controller.updateProfile);
router.get("/:id/submissions",requireRoles(...[...instituteEditors,...reviewers]),requireResourceScope("ITI"), validate({params:itiIdParamsSchema}),controller.list);
router.post("/:id/submissions",requireRoles(...instituteEditors),requireResourceScope("ITI"), validate({params:itiIdParamsSchema,body:createItiSubmissionSchema}),controller.create);
router.patch("/:id/submissions/:submissionId",requireRoles(...instituteEditors),requireResourceScope("ITI"), validate({params:itiSubmissionParamsSchema,body:updateItiSubmissionSchema}),controller.update);
router.post("/:id/submissions/:submissionId/submit",requireRoles(...instituteEditors),requireResourceScope("ITI"), validate({params:itiSubmissionParamsSchema}),controller.submit);
router.post("/:id/submissions/:submissionId/review",requireRoles(...reviewers),requireResourceScope("ITI"), validate({params:itiSubmissionParamsSchema,body:reviewItiSubmissionSchema}),controller.review);
export default router;
