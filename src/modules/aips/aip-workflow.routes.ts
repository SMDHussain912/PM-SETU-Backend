import {Router} from "express";
import {requireAuth} from "../../middleware/auth.middleware";
import {requireRoles} from "../../middleware/rbac.middleware";
import {requireResourceScope} from "../../middleware/scope.middleware";
import {validate} from "../../middleware/validate.middleware";
import {ROLE_CODES} from "../roles/role.constants";
import * as c from "./aip-workflow.controller";
import {aipReportParamsSchema,aipWorkflowParamsSchema,createAipActivitySchema,createAipReportSchema,reviewAipReportSchema,updateAipReportSchema} from "./aip-workflow.schema";
const r=Router();
const editors=[ROLE_CODES.AIP_USER,ROLE_CODES.SUPER_ADMIN,ROLE_CODES.STATE_PMU_ADMIN];
const reviewers=[ROLE_CODES.CLUSTER_ADMIN,ROLE_CODES.STATE_PMU_ADMIN,ROLE_CODES.SUPER_ADMIN];
r.use(requireAuth);
r.get("/:id/activities",requireRoles(...[...editors,...reviewers]),validate({params:aipWorkflowParamsSchema}),requireResourceScope("AIP"),c.activities);
r.post("/:id/activities",requireRoles(...editors),validate({params:aipWorkflowParamsSchema,body:createAipActivitySchema}),requireResourceScope("AIP"),c.addActivity);
r.get("/:id/submissions",requireRoles(...[...editors,...reviewers]),validate({params:aipWorkflowParamsSchema}),requireResourceScope("AIP"),c.reports);
r.post("/:id/submissions",requireRoles(...editors),validate({params:aipWorkflowParamsSchema,body:createAipReportSchema}),requireResourceScope("AIP"),c.createReport);
r.patch("/:id/submissions/:submissionId",requireRoles(...editors),validate({params:aipReportParamsSchema,body:updateAipReportSchema}),requireResourceScope("AIP"),c.updateReport);
r.post("/:id/submissions/:submissionId/submit",requireRoles(...editors),validate({params:aipReportParamsSchema}),requireResourceScope("AIP"),c.submitReport);
r.post("/:id/submissions/:submissionId/review",requireRoles(...reviewers),validate({params:aipReportParamsSchema,body:reviewAipReportSchema}),requireResourceScope("AIP"),c.reviewReport);
export default r;
